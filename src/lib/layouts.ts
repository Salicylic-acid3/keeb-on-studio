import type {
  PhysicalLayout,
  KeyPhysicalAttrs,
} from "@zmkfirmware/zmk-studio-ts-client/keymap";

/**
 * Physical layouts for demo mode.
 *
 * A connected keyboard reports its own layout over the Studio protocol, so
 * these exist only to give the demo transport something to draw. They are
 * transcribed from each keyboard's `*-layouts.dtsi` in its firmware
 * repository, in the units the firmware uses (100 = 1u, rotation in
 * centi-degrees), so demo mode shows the keyboards this app is actually for.
 *
 * Generated from those files rather than measured by hand. The layouts these
 * replaced -- carried over from upstream, for keyboards this app does not
 * support -- declared two keys at the same position, which is why the demo
 * used to draw keys on top of each other.
 */

function attr(partialAttr: Partial<KeyPhysicalAttrs>): KeyPhysicalAttrs {
  return {
    width: 0,
    height: 0,
    x: 0,
    y: 0,
    r: 0,
    rx: 0,
    ry: 0,
    ...partialAttr,
  };
}

